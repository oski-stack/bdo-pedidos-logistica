-- Esquema inicial. Flyway es el dueño del esquema; Hibernate solo lo valida (ddl-auto=validate, D9).

CREATE TABLE cliente (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL,
    email VARCHAR(254) NOT NULL UNIQUE
);

CREATE TABLE pedido (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id BIGINT NOT NULL,
    codigo_postal_destino VARCHAR(5) NOT NULL,
    estado VARCHAR(20) NOT NULL,
    -- WITH TIME ZONE: se mapean a Instant y representan instantes absolutos.
    fecha TIMESTAMP WITH TIME ZONE NOT NULL,
    importe_productos NUMERIC(19, 2) NOT NULL,
    -- Nulos hasta que el pedido está CONFIRMADO (D2, D7).
    coste_envio NUMERIC(19, 2),
    importe_total NUMERIC(19, 2),
    -- Lo rellena la reserva atómica al pasar a CONFIRMANDO (D4).
    confirmacion_iniciada_en TIMESTAMP WITH TIME ZONE,
    -- Bloqueo optimista (@Version). La reserva la incrementa explícitamente (D4).
    version BIGINT NOT NULL,
    -- La entidad solo guarda cliente_id (sin relación JPA, D2), pero la BD mantiene la integridad.
    CONSTRAINT fk_pedido_cliente FOREIGN KEY (cliente_id) REFERENCES cliente (id)
);

-- Líneas del pedido (@ElementCollection): sin id propio; posicion es la @OrderColumn.
CREATE TABLE linea_pedido (
    pedido_id BIGINT NOT NULL,
    posicion INTEGER NOT NULL,
    producto VARCHAR(160) NOT NULL,
    cantidad INTEGER NOT NULL,
    precio_unitario NUMERIC(19, 2) NOT NULL,
    peso_unitario_kg NUMERIC(10, 3) NOT NULL,
    PRIMARY KEY (pedido_id, posicion),
    -- Las líneas no existen sin su pedido.
    CONSTRAINT fk_linea_pedido_pedido FOREIGN KEY (pedido_id) REFERENCES pedido (id) ON DELETE CASCADE
);

CREATE INDEX idx_pedido_cliente ON pedido (cliente_id);
CREATE INDEX idx_pedido_estado ON pedido (estado);
